def spectrum_strip(d, box, wl0=380, wl1=780):
    """按波长着色的色带（颜色由等色函数算出）。"""
    x0, y0, x1, y1 = box
    n = int((x1 - x0) * SS)
    for i in range(n):
        wl = wl0 + (wl1 - wl0) * i / max(1, n - 1)
        rgb = wavelength_rgb(wl) if 380 <= wl <= 700 else None
        if rgb is None:
            # 可见光两端之外：按到端点的距离渐暗
            edge = 380 if wl < 380 else 700
            base = wavelength_rgb(edge)
            k = max(0.0, 1 - abs(wl - edge) / 60.0) * 0.8
            rgb = tuple(int(v * k) for v in base)
        d.line([(x0 * SS + i, y0 * SS), (x0 * SS + i, y1 * SS)], fill=rgb, width=1)
    rect(d, box, outline=BORDER)



def horseshoe_image(w, h, xmax=0.8, ymax=0.9, Y=None):
    """把色度图的马蹄形画成一张 w×h 的 RGBA 位图，覆盖数据范围 0..xmax × 0..ymax。

    Y 为 None 时每个色度取『尽可能亮』的显示色；给定 Y（0..1）时按该绝对亮度
    换算，超出 sRGB 的分量直接裁剪。全部用 numpy 一次算完。
    """
    locus = spectral_locus(1)
    mask = Image.new("L", (w, h), 0)
    ImageDraw.Draw(mask).polygon(
        [(x / xmax * w, h - y / ymax * h) for _, x, y in locus], fill=255)
    m = np.array(mask) > 0
    xs = (np.arange(w) + 0.5) / w * xmax
    ys = (h - (np.arange(h) + 0.5)) / h * ymax
    x, y = np.meshgrid(xs, ys)
    y = np.maximum(y, 1e-4)
    Yv = 1.0 if Y is None else Y
    xyz = np.stack([Yv * x / y, np.full_like(x, Yv), Yv * (1 - x - y) / y], axis=-1)
    rgb = xyz @ M_XYZ2RGB.T
    if Y is None:
        rgb = rgb - np.minimum(0.0, rgb.min(axis=-1, keepdims=True))
        rgb = rgb / rgb.max(axis=-1, keepdims=True)
    out = np.zeros((h, w, 4), dtype=np.uint8)
    out[..., :3] = (_encode(rgb) * 255 + 0.5).astype(np.uint8)
    out[..., 3] = np.where(m, 255, 0)
    return Image.fromarray(out, "RGBA")


_HS_CACHE = {}



def horseshoe(w, h, xmax=0.8, ymax=0.9, Y=None):
    key = (w, h, xmax, ymax, Y)
    if key not in _HS_CACHE:
        _HS_CACHE[key] = horseshoe_image(w, h, xmax, ymax, Y)
    return _HS_CACHE[key]


