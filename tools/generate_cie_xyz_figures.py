    R = 0.9
    size = 300 * SS
    hs = horseshoe(size, size, R, R)
    locus = spectral_locus(2)

    def warp(o, on_plane, alpha=255):
        """把马蹄形位图仿射变换到 3-D 场景里：on_plane=True 贴在 x+y+z=1 上，
        否则贴在 z=0 的 xy 平面上。(x, y) -> (x, y, 1-x-y) 与 (x, y) -> (x, y, 0)
        再经平行投影，都是仿射映射，所以一次仿射变换就能画准。"""
        def img_to_screen(u, v):
            x = u / size * R
            y = (size - v) / size * R
            z = (1 - x - y) if on_plane else 0.0
            return _proj3(x, y, z, o)
        src = np.array([[0, 0], [size, 0], [0, size]], dtype=float)
        dst = np.array([img_to_screen(*p) for p in src], dtype=float) * SS
        A = np.linalg.solve(np.c_[src, np.ones(3)], dst)
        M = np.array([[A[0, 0], A[1, 0], A[2, 0]], [A[0, 1], A[1, 1], A[2, 1]], [0, 0, 1]])
        Mi = np.linalg.inv(M)
        layer = hs
        if alpha != 255:
            layer = hs.copy()
            a = layer.getchannel("A").point(lambda v: v * alpha // 255)
            layer.putalpha(a)
        warped = layer.transform(im.size, Image.AFFINE, tuple(Mi[:2].ravel()), resample=Image.BILINEAR)
        im.paste(warped, (0, 0), warped)

    def axes_and_plane(o, wall_grid):
        if wall_grid:
            for k in range(0, 10):
                if k <= 8:
                    a = _proj3(k / 10, 0, 0, o); b = _proj3(k / 10, R, 0, o)
                    line(d, (a[0], a[1], b[0], b[1]), fill=GRID)
                a = _proj3(0, k / 10, 0, o); b = _proj3(0.8, k / 10, 0, o)
                line(d, (a[0], a[1], b[0], b[1]), fill=GRID)
        for (vec, lab, off) in [((1.25, 0, 0), "x", (14, 0)), ((0, 1.2, 0), "y", (0, -14)),
                                ((0, 0, 1.25), "z", (-14, 8))]:
            p = _proj3(*vec, o)
            arrow(d, _proj3(0, 0, 0, o), p, fill=INK, width=1.6, head=9)
            text(d, (p[0] + off[0], p[1] + off[1]), lab, fi)
        tri = [_proj3(1, 0, 0, o), _proj3(0, 1, 0, o), _proj3(0, 0, 1, o)]
        poly(d, tri, outline=MUTED, width=1.2)
        for v, off in [((1, 0, 0), (0, 12)), ((0, 1, 0), (12, 0)), ((0, 0, 1), (14, 4))]:
            p = _proj3(*v, o)
            text(d, (p[0] + off[0], p[1] + off[1]), "1", f, fill=MUTED)

    # 左：马蹄形贴在 x + y + z = 1 的平面上
    oL = (250, 340)
    axes_and_plane(oL, wall_grid=False)
    warp(oL, on_plane=True)
    pts = [_proj3(x, y, 1 - x - y, oL) for _, x, y in locus]
    polyline(d, pts + [pts[0]], fill=INK, width=1.2)

    # 右：同一场景，沿 z 轴方向把每个点压到 z = 0 的 xy 平面上
    oR = (745, 340)
    axes_and_plane(oR, wall_grid=True)
    warp(oR, on_plane=False)                      # 影子（xy 平面上的色度图）
    # 原来的马蹄形只留轮廓，免得两块颜色叠在一起看不清
    pts3 = [_proj3(x, y, 1 - x - y, oR) for _, x, y in locus]
    pts0 = [_proj3(x, y, 0, oR) for _, x, y in locus]
    polyline(d, pts3 + [pts3[0]], fill=MUTED, width=1.0)
    polyline(d, pts0 + [pts0[0]], fill=INK, width=1.2)
    # 投影线：几个代表点沿 z 轴方向落到后壁
    for wl in (380, 480, 520, 580, 700):
        X, Yv, Z = cmf_at(wl)
        ssum = X + Yv + Z
        x, y = X / ssum, Yv / ssum
        p3 = _proj3(x, y, 1 - x - y, oR)
        p0 = _proj3(x, y, 0, oR)
        dashed(d, p3, p0, fill=ACCENT, width=1.2, dash=5, gap=4)
        ellipse(d, (p3[0] - 3, p3[1] - 3, p3[0] + 3, p3[1] + 3), fill=ACCENT)
        ellipse(d, (p0[0] - 3, p0[1] - 3, p0[0] + 3, p0[1] + 3), fill=INK)

    arrow(d, (500, 150), (620, 150), fill=CURVE, width=8, head=18)
    text(d, (560, 120), "沿 z 轴方向投影到 xy 平面", font(15, bold=True), fill=CURVE)
    text(d, (560, 178), "(x, y, z) → (x, y, 0)", font(14), fill=CURVE)
    text(d, (300, 570), "x + y + z = 1 平面上的马蹄形", f)
    text(d, (790, 570), "落在 xy 平面上的影子，就是 xy 色度图", f)
    text(d, (790, 592), "（虚线为投影线，与 z 轴平行）", fs, fill=MUTED)
    finish(im, os.path.join(out, "xyz-plane-projection.png"))


