def arrow(d, p0, p1, fill=INK, width=3, head=11):
    x0, y0 = p0
    x1, y1 = p1
    ang = math.atan2(y1 - y0, x1 - x0)
    bx, by = x1 - head * math.cos(ang), y1 - head * math.sin(ang)
    line(d, (x0, y0, bx, by), fill=fill, width=width)
    w = head * 0.46
    poly(d, [(x1, y1),
             (bx - w * math.sin(ang), by + w * math.cos(ang)),
             (bx + w * math.sin(ang), by - w * math.cos(ang))], fill=fill)


def dashed(d, p0, p1, fill=MUTED, width=1, dash=7, gap=5):
    x0, y0 = p0
    x1, y1 = p1
    total = math.hypot(x1 - x0, y1 - y0)
    if total == 0:
        return
    ux, uy = (x1 - x0) / total, (y1 - y0) / total
    t = 0.0
    while t < total:
        e = min(t + dash, total)
        line(d, (x0 + ux * t, y0 + uy * t, x0 + ux * e, y0 + uy * e),
             fill=fill, width=width)
        t = e + gap


def callout(d, box, s, f, fill=(252, 250, 232), outline=(224, 214, 170),
            text_fill=INK, radius=8, tail=None):
    rect(d, box, fill=fill, outline=outline, radius=radius)
    x0, y0, x1, y1 = box
    lines = s.split("\n")
    lh = f.size / SS * 1.42
    cy = (y0 + y1) / 2 - (len(lines) - 1) * lh / 2
    for i, ln in enumerate(lines):
        text(d, ((x0 + x1) / 2, cy + i * lh), ln, f, fill=text_fill)
    if tail:
        tx, ty = tail
        cx, cyy = (x0 + x1) / 2, (y0 + y1) / 2
        ang = math.atan2(ty - cyy, tx - cx)
        ex = cx + math.cos(ang) * (x1 - x0) / 2
        ey = cyy + math.sin(ang) * (y1 - y0) / 2
        line(d, (ex, ey, tx, ty), fill=outline, width=1.4)


class Axes:
    """最简单的二维坐标框：把数据坐标映射到像素。"""

    def __init__(self, d, box, xr, yr):
        self.d, self.box, self.xr, self.yr = d, box, xr, yr

    def px(self, x, y):
        x0, y0, x1, y1 = self.box
        return (x0 + (x - self.xr[0]) / (self.xr[1] - self.xr[0]) * (x1 - x0),
                y1 - (y - self.yr[0]) / (self.yr[1] - self.yr[0]) * (y1 - y0))

    def frame(self, xticks, yticks, fx, xfmt="%g", yfmt="%g", grid=True,
              xlabel=None, ylabel=None):
        x0, y0, x1, y1 = self.box
        rect(self.d, self.box, fill=PANEL)
        for xv in xticks:
            px, _ = self.px(xv, self.yr[0])
            if grid:
                line(self.d, (px, y0, px, y1), fill=GRID)
            text(self.d, (px, y1 + 12), xfmt % xv, fx, fill=MUTED, anchor="mt")
        for yv in yticks:
            _, py = self.px(self.xr[0], yv)
            if grid:
                line(self.d, (x0, py, x1, py), fill=GRID)
            text(self.d, (x0 - 8, py), yfmt % yv, fx, fill=MUTED, anchor="rm")
        rect(self.d, self.box, outline=BORDER, width=1.2)
        if xlabel:
            text(self.d, ((x0 + x1) / 2, y1 + 34), xlabel, fx, fill=INK, anchor="mt")
        if ylabel:
            text(self.d, (x0 - 8, y0 - 10), ylabel, fx, fill=INK, anchor="rb")

    def grid(self, xticks, yticks):
        """只重画网格线（用于在框内另外铺了底色之后）。"""
        x0, y0, x1, y1 = self.box
        for xv in xticks:
            px, _ = self.px(xv, self.yr[0])
            line(self.d, (px, y0, px, y1), fill=GRID)
        for yv in yticks:
            _, py = self.px(self.xr[0], yv)
            line(self.d, (x0, py, x1, py), fill=GRID)
        rect(self.d, self.box, outline=BORDER, width=1.2)

    def plot(self, xs, ys, fill=CURVE, width=2.2):
        pts = [self.px(x, y) for x, y in zip(xs, ys)]
        polyline(self.d, pts, fill=fill, width=width)


