def _proj3(x, y, z, origin, sx=240, sy=250, sz=(-110, 150)):
    """简单的斜投影：x 向右，y 向上，z 朝观察者、画成向左下（与原文一致）。
    sz 是 z 每增加 1 在屏幕上的位移：向左 110、向下 150。"""
    ox, oy = origin
    return (ox + x * sx + z * sz[0], oy - y * sy + z * sz[1])



