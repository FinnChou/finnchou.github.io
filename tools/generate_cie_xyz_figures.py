_LOCUS_POLY = None


def _inside_locus(x, y):
    """点是否在光谱轨迹 + 纯紫轨迹围成的区域内（射线法）。"""
    global _LOCUS_POLY
    if _LOCUS_POLY is None:
        _LOCUS_POLY = [(px, py) for _, px, py in spectral_locus(2)]
    inside = False
    n = len(_LOCUS_POLY)
    for i in range(n):
        xa, ya = _LOCUS_POLY[i]
        xb, yb = _LOCUS_POLY[(i + 1) % n]
        if (ya > y) != (yb > y):
            xi = xa + (y - ya) / (yb - ya) * (xb - xa)
            if xi > x:
                inside = not inside
    return inside


