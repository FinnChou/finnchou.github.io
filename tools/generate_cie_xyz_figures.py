    im, d = canvas(W, H)
    fx = font(13)
    ax = Axes(d, (90, 60, 900, 410), (300, 780), (0, ymax))
    xt, yt = list(range(300, 781, 40)), [i * ymax / 5 for i in range(6)]
    ax.frame(xt, yt, fx, yfmt="%g", ylabel="相对光谱功率")
    # 可见光范围铺浅底色，然后把网格重画在底色之上
    x0, _ = ax.px(380, 0)
    x1, _ = ax.px(780, 0)
    rect(d, (x0, 60, x1, 410), fill=(246, 247, 252))
    ax.grid(xt, yt)
    ax.plot(wl, spd, fill=CURVE, width=2.6)
    spectrum_strip(d, (x0, 440, x1, 458))
    text(d, ((x0 + x1) / 2, 480), "波长 (nm)", font(15))
    text(d, ((ax.px(300, 0)[0] + x0) / 2, 449), "紫外", fx, fill=MUTED)
    text(d, (495, 30), title, font(17, bold=True))
    text(d, (495, 506), note, fx, fill=MUTED)
    finish(im, os.path.join(out, name))


