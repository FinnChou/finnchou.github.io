def _parse(block):
    rows = [ln.split() for ln in block.strip().splitlines()]
    wl = np.array([float(r[0]) for r in rows])
    val = np.array([[float(v) for v in r[1:]] for r in rows])
    return wl, (val[:, 0] if val.shape[1] == 1 else val)


