def cmf_at(wl):
    """等色函数在任意波长处的取值（线性插值）。"""
    return np.array([np.interp(wl, WL_CMF, CMF[:, i]) for i in range(3)])


# ------------------------------------------------------------------ 颜色换算
M_XYZ2RGB = np.array([[3.2406, -1.5372, -0.4986],
                      [-0.9689, 1.8758, 0.0415],
                      [0.0557, -0.2040, 1.0570]])


def _encode(rgb_linear):
    v = np.clip(rgb_linear, 0.0, 1.0)
    return np.where(v <= 0.0031308, v * 12.92, 1.055 * v ** (1 / 2.4) - 0.055)


def xyz_to_srgb8(xyz):
    rgb = M_XYZ2RGB @ np.asarray(xyz, dtype=float)
    return tuple(int(round(v * 255)) for v in _encode(rgb))


def xyY_to_XYZ(x, y, Y):
    return np.array([Y * x / y, Y, Y * (1 - x - y) / y])


def chroma_rgb(x, y):
    """给定色度 (x, y)，返回『尽可能亮』的 sRGB 显示色。

    色度图上的颜色只规定了 (x, y)，不规定亮度，惯例是取 sRGB 里能显示的最亮
    的那个；落在 sRGB 色域之外的色度按比例压回色域边界，只能算近似。
    """
    xyz = xyY_to_XYZ(x, y, 1.0)
    rgb = M_XYZ2RGB @ xyz
    rgb = rgb - min(0.0, rgb.min())        # 负分量整体抬到 0（色域外近似）
    rgb = rgb / rgb.max()
    return tuple(int(round(v * 255)) for v in _encode(rgb))


def spectral_locus(step=1):
    """光谱轨迹 (x, y)，380–700 nm。"""
    pts = []
    for wl in range(380, 701, step):
        X, Y, Z = cmf_at(wl)
        s = X + Y + Z
        pts.append((wl, X / s, Y / s))
    return pts


def wavelength_rgb(wl):
    """单色光的显示色：由等色函数算出色度，再取最亮的 sRGB。"""
    X, Y, Z = cmf_at(wl)
    s = X + Y + Z
    return chroma_rgb(X / s, Y / s)


def tristimulus(wl, spd, refl=None):
    """按 CIE 15 定义算三刺激值，k 取使完全漫反射体 Y = 100 的归一化常数。"""
    c = cmf_at(wl)
    p = spd if refl is None else spd * refl
    k = 100.0 / np.trapezoid(spd * c[1], wl)
    return np.array([k * np.trapezoid(p * c[i], wl) for i in range(3)])


