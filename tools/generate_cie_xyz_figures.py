    fs = font(12)

    R = 0.9                       # 位图覆盖的数据范围 0..R
    size = 320 * SS
    hs_cache = {}

    def layer_map(x, y, base_y):
        """数据 (x, y) -> 屏幕坐标：把色度图平放成一个倾斜的平行四边形。"""
        ox, wd, hd, shear = 190, 300, 120, 0.42
        u, v = x / R, y / R
        return (ox + u * wd + v * hd * shear, base_y - v * hd)

    layers = [(0.05, 500), (0.20, 350), (0.50, 200)]
    for Y, base_y in layers:
        hs = horseshoe(size, size, R, R, Y)
        # 位图 (u, v) 像素 -> 屏幕，仿射；PIL 需要逆映射
        src = np.array([[0, 0], [size, 0], [0, size]], dtype=float)
        dst = np.array([layer_map(u / size * R, (size - v) / size * R, base_y)
                        for u, v in src]) * SS
        A = np.linalg.solve(np.c_[src, np.ones(3)], dst)
        M = np.array([[A[0, 0], A[1, 0], A[2, 0]], [A[0, 1], A[1, 1], A[2, 1]], [0, 0, 1]])
        Mi = np.linalg.inv(M)
        warped = hs.transform(im.size, Image.AFFINE, tuple(Mi[:2].ravel()), resample=Image.BILINEAR)
        im.paste(warped, (0, 0), warped)
        lx, ly = layer_map(0, 0.45, base_y)
