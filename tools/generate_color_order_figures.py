# 图 6：5R 的等色相面
# ==========================================================================
def fig_hue_page(out):
    W, H = 1020, 780
    im, d = canvas(W, H)
    f_t, f_s, f_a = font(17, True), font(13), font(14)
    CMAX = 20
    x0, y0 = 188, 130
    cw, ch = 38, 50

    def cell(c, v):
        cx_ = x0 + (c / 2) * cw
        cy_ = y0 + (10 - v) * ch
        return (cx_, cy_, cx_ + cw - 4, cy_ + ch - 4)

    for c in range(2, CMAX + 1, 2):             # 先铺空格子
        for v in range(0, 11):
            if v in (0, 10) or c not in {k for k, _, _ in hue_chips("5R", v)}:
                checker(d, cell(c, v))
                rect(d, cell(c, v), outline=(214, 218, 230), width=1)

    for v in range(0, 11):                      # 无彩色轴（C=0）
        Y = 100.0 / 0.975 if v == 10 else (0.0 if v == 0 else MUNSELL_VY[v])
        rect(d, cell(0, v), fill=gray_srgb(Y), outline=(160, 165, 182), width=1)
        text(d, (x0 - 14, cell(0, v)[1] + (ch - 4) / 2), "%d/" % v, f_s,
             fill=INK, anchor="rm")

    steps = {}
    for v in range(1, 10):
        for c, rgb, inside in hue_chips("5R", v):
            if c <= CMAX:
                rect(d, cell(c, v), fill=rgb, outline=(160, 165, 182), width=1)
        ins = [c for c, _, i in hue_chips("5R", v) if i and c <= CMAX]
        if ins:
            steps[v] = cell(max(ins), v)[2] + 2

    # sRGB 色域边界：做成规整的阶梯线
    path = []
    for v in sorted(steps):
        yb, yt = cell(0, v)[1] + ch - 2, cell(0, v)[1] - 2
        if path:
            path.append((steps[v], path[-1][1]))
        path.append((steps[v], yb))
        path.append((steps[v], yt))
    if path:
        d.line([(x * SS, y * SS) for x, y in path], fill=(52, 54, 68),
               width=int(2.0 * SS))
        callout(d, (664, 286, 1000, 366),
                "深色折线右侧的色卡超出 sRGB 色域，\n屏幕上只能压缩到色域边界显示", f_s,
                tail=(steps[6] + 4, cell(0, 6)[1] + ch / 2))

    for c in range(0, CMAX + 1, 2):
        text(d, (cell(c, 0)[0] + (cw - 4) / 2, y0 + 11 * ch + 4), "/%d" % c,
             f_s, fill=MUTED)
    text(d, (x0 - 64, y0 + 5.5 * ch), "明\n度\nV", f_a, fill=INK)
    text(d, ((x0 + cell(CMAX, 0)[2]) / 2, y0 + 11 * ch + 34), "彩度 C", f_a, fill=INK)
    text(d, (30, 32), "5R 的等色相面（明度 x 彩度）", f_t, fill=INK, anchor="lm")
    text(d, (30, 58), "浅灰棋盘格 = 该位置没有对应的色卡", f_s, fill=MUTED, anchor="lm")
    finish(im, os.path.join(out, "munsell-hue-page-5R.png"))


