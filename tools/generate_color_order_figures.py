# ==========================================================================
# 色度换算：xyY(照明体 C) -> sRGB
#   Bradford 色适应 C -> D65，再用 IEC 61966-2-1 的 sRGB 矩阵与传递函数。
# ==========================================================================
M_XYZ2RGB = np.array([[3.2404542, -1.5371385, -0.4985314],
                      [-0.9692660, 1.8760108, 0.0415560],
                      [0.0556434, -0.2040259, 1.0572252]])
M_BRADFORD = np.array([[0.8951, 0.2664, -0.1614],
                       [-0.7502, 1.7135, 0.0367],
                       [0.0389, -0.0685, 1.0296]])


def _white(x, y):
    return np.array([x / y, 1.0, (1 - x - y) / y])


_WP_C = _white(0.31006, 0.31616)      # CIE 标准照明体 C
_WP_D65 = _white(0.31272, 0.32903)    # CIE 标准照明体 D65（sRGB 的白点）
_M_ADAPT = (np.linalg.inv(M_BRADFORD)
            @ np.diag((M_BRADFORD @ _WP_D65) / (M_BRADFORD @ _WP_C))
            @ M_BRADFORD)


def _encode(rgb_linear):
    v = np.clip(rgb_linear, 0.0, 1.0)
    return np.where(v <= 0.0031308, v * 12.92, 1.055 * v ** (1 / 2.4) - 0.055)


def munsell_srgb(x, y, Y_mgo):
    """曼塞尔 renotation 的 xyY 换成 sRGB。

    返回 (颜色, 是否落在 sRGB 色域内)。Y_mgo 是以氧化镁为基准的百分数，
    乘 0.975 换算到以完全漫反射体为基准的绝对反射率。
    """
    Y = Y_mgo * 0.975 / 100.0
    xyz = np.array([Y * x / y, Y, Y * (1 - x - y) / y])
    rgb = M_XYZ2RGB @ (_M_ADAPT @ xyz)
    inside = bool(np.all(rgb > -0.002) and np.all(rgb < 1.002))
    return tuple(int(round(v * 255)) for v in _encode(rgb)), inside


def gray_srgb(Y_mgo):
    """给定视感反射率（相对 MgO），返回对应的中性灰 sRGB。"""
    Y = np.clip(Y_mgo * 0.975 / 100.0, 0.0, 1.0)
    v = float(_encode(np.array([Y]))[0])
    g = int(round(v * 255))
    return (g, g, g)


def hue_chips(hue, value):
    """取某色相某明度下所有真实存在的色卡，返回 [(C, sRGB, 是否在色域内)]。"""
    s = MUNSELL_XY.get(hue, {}).get(value)
    if not s:
        return []
    out = []
    for item in s.split():
        c, x, y = item.split(",")
        rgb, inside = munsell_srgb(float(x), float(y), MUNSELL_VY[value])
        out.append((int(c), rgb, inside))
    return out


def astm_value_to_Y(V):
    """ASTM D1535 的明度 -> 视感反射率五次式（基准为完全漫反射体，单位 %）。"""
    return (1.1914 * V - 0.22533 * V ** 2 + 0.23352 * V ** 3
            - 0.020484 * V ** 4 + 0.00081939 * V ** 5)


